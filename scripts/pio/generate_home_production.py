"""Generate a namespaced build adapter from the protected canonical home rig.
No motion algorithm edits, raster processing, or changes to the trial catalog.
Run --check to verify committed/generated bytes without changing anything.
"""
from pathlib import Path
import json, hashlib, sys
root = Path(__file__).resolve().parents[2]
check = '--check' in sys.argv
source = root/'Daylog/Components/PioOverhaulCharacter.swift'
src = source.read_text()
body = src[src.index('enum PioOverhaulAction:'):src.index('struct PioOverhaulCharacterView:')]
body = body.replace('PioOverhaul','PioHomeProduction').replace('pio_overhaul_', 'pio_home_production_')
header = '// GENERATED by scripts/pio/generate_home_production.py; do not edit motion algorithms here.\n// Canonical source SHA256: '+hashlib.sha256(source.read_bytes()).hexdigest()+'\nimport SwiftUI\nimport QuartzCore\n#if os(macOS)\nimport AppKit\n#else\nimport UIKit\n#endif\n\n'
outputs = {root/'Daylog/Components/PioHomeProductionRig.swift': (header+body).encode()}
trial = root/'Daylog/PioOverhaulTrial.xcassets'
catalog = root/'Daylog/PioHomeProduction.xcassets'
outputs[catalog/'Contents.json'] = b'{"info":{"author":"xcode","version":1}}\n'
entries=[]
canonical={}
for registration in sorted(trial.glob('pio_overhaul_*_registration.dataset/registration.json')):
    data=json.loads(registration.read_bytes())
    target=catalog/registration.parent.name.replace('pio_overhaul_','pio_home_production_')
    for p in data['parts']:
        old=p['asset']; candidate=old.replace('pio_overhaul_','pio_home_production_')
        origin=trial/(old+'.imageset')
        png=next(origin.glob('*.png')); digest=hashlib.sha256(png.read_bytes()).hexdigest()
        new=canonical.setdefault(digest,candidate); p['asset']=new
        for f in origin.iterdir():
            content=f.read_bytes()
            name=f.name.replace(old,new)
            if f.suffix=='.json': content=content.replace(old.encode(),new.encode())
            outputs[catalog/(new+'.imageset')/name]=content
            if f.suffix=='.png': entries.append({'source':str(f.relative_to(root)),'target':str((catalog/(new+'.imageset')/name).relative_to(root)),'sha256':hashlib.sha256(content).hexdigest()})
    outputs[target/'registration.json']=(json.dumps(data,ensure_ascii=False,indent=2)+'\n').encode()
    outputs[target/'Contents.json']=(registration.parent/'Contents.json').read_bytes()
outputs[root/'docs/qa/pio-character-final-pass-2026-10-24/home-production-provenance.json']=(json.dumps({'source':str(source.relative_to(root)),'sourceSHA256':hashlib.sha256(source.read_bytes()).hexdigest(),'method':'Namespace/prefix substitutions only; identical SHA256 PNG references share a canonical asset name. Motion algorithms and image bytes unchanged.','assets':entries},indent=2)+'\n').encode()
for p,data in outputs.items():
    if check:
        assert p.exists() and p.read_bytes()==data, str(p)
    else:
        p.parent.mkdir(parents=True,exist_ok=True);p.write_bytes(data)
print(('Verified' if check else 'Generated'),len(entries),'PNG copies;',len(outputs),'files')
